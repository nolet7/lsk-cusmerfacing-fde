-- Apply once through a reviewed migration job before starting an enterprise gateway.
-- Separate DB roles: migration owner owns schema; runtime role has only SELECT/INSERT
-- on investigations and USAGE on the sequence.
CREATE TABLE IF NOT EXISTS investigations (
 investigation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id varchar(64) NOT NULL,
 order_id varchar(64) NOT NULL,
 reason_code varchar(64) NOT NULL,
 note varchar(1000) NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'OPEN',
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK (status IN ('OPEN','IN_REVIEW','RESOLVED'))
);
CREATE INDEX IF NOT EXISTS idx_investigations_tenant_id
ON investigations (tenant_id, investigation_id DESC);
